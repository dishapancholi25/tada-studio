# 6. Chat memory sync path also redacts before persisting (fixed bypass)
# ---------------------------------------------------------------------------
class TestChatMemorySyncRedaction:
    def test_store_chat_turn_sync_redacts_before_persisting(self):
        """The executor-thread write path must redact just like the async one."""
        import json

        from backend.services.chat.memory import ChatMemoryService

        captured_rows = []

        class _FakeDB:
            def add(self, obj):
                captured_rows.append(obj)

            def commit(self):
                pass

            def __enter__(self):
                return self

            def __exit__(self, *a):
                return False

        with patch(
            "backend.services.chat.memory.get_db", return_value=_FakeDB()
        ):
            service = ChatMemoryService()
            service.store_chat_turn_sync(
                chat_session_id="sess-1",
                user_message="my SSN is 219-09-9999",
                assistant_response="noted",
                graph_execution_id="exec-1",
                workflow_name="TestWorkflow",
            )

        assert len(captured_rows) == 2
        raw_contents = " ".join(row.content for row in captured_rows)
        assert "219-09-9999" not in raw_contents
        assert "US_SSN" in raw_contents
        # Redacted content must remain valid JSON so history loading still parses it.
        for row in captured_rows:
            parsed = json.loads(row.content)
            assert "role" in parsed and "content" in parsed
