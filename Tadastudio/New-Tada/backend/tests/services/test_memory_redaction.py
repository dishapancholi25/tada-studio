# ---------------------------------------------------------------------------
# 4. Repository refuses to persist unredacted content
# ---------------------------------------------------------------------------
class TestRepositoryGuard:
    @pytest.mark.asyncio
    async def test_create_memory_rejects_unredacted_payload(self):
        memory_data = MemoryCreate(
            agent_id="agent-1",
            agent_name="Assistant",
            memory_type="conversation",
            content="raw content, never redacted",
            redacted=False,
        )
        with pytest.raises(MemoryStorageError, match="not redacted"):
            await MemoryRepository.create_memory(memory_data)

    @pytest.mark.asyncio
    async def test_create_memory_accepts_redacted_payload(self):
        """Passing the redacted marker clears the guard (DB layer itself is mocked)."""
        memory_data = MemoryCreate(
            agent_id="agent-1",
            agent_name="Assistant",
            memory_type="conversation",
            content="⟦PII:EMAIL_ADDRESS:v1:abc⟧",
            redacted=True,
        )
        with patch("backend.services.memory.repository.get_db") as mock_get_db:
            mock_db = mock_get_db.return_value.__enter__.return_value
            mock_db.add = lambda obj: None
            mock_db.commit = lambda: None
            mock_db.refresh = lambda obj: None
            result = await MemoryRepository.create_memory(memory_data)
            assert result.content == "⟦PII:EMAIL_ADDRESS:v1:abc⟧"


# ---------------------------------------------------------------------------
# 5. Manager funnels every create_memory call through the redaction hook
# ---------------------------------------------------------------------------
class TestManagerFunnel:
    @pytest.mark.asyncio
    async def test_create_memory_redacts_before_persisting(self):
        from backend.services.memory.manager import MemoryManager

        manager = MemoryManager()
        captured: dict = {}

        async def fake_create_memory(memory_data: MemoryCreate):
            captured["memory_data"] = memory_data

            class _Row:
                content = memory_data.content

            return _Row()

        manager.repository.create_memory = AsyncMock(side_effect=fake_create_memory)

        await manager.create_memory(
            agent_id="agent-1",
            agent_name="Assistant",
            memory_type="conversation",
            content="my email is bob@example.com",
        )

        sent: MemoryCreate = captured["memory_data"]
        assert sent.redacted is True
        assert "bob@example.com" not in sent.content
        assert "EMAIL_ADDRESS" in sent.content


