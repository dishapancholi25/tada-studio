"""Tests for post-write memory redaction (User Story 5965 / Task 5966).

Proves:
    * PII and secrets are never persisted in original plaintext form.
    * Normal (non-sensitive) content is unaffected and round-trips.
    * The repository refuses to persist content that wasn't redacted.
    * The manager funnels every ``create_memory`` call through the hook.
    * ``ChatMemoryService.store_chat_turn_sync`` also redacts before persisting.

``MEMORY_ENCRYPTION_KEY`` / ``CREDENTIAL_ENCRYPTION_KEY`` are auto-generated by
``CredentialEncryption`` under ``PYTEST_CURRENT_TEST``, so no env setup is needed.
"""

from __future__ import annotations

from unittest.mock import AsyncMock, patch

import pytest

from backend.services.memory.exceptions import MemoryStorageError
from backend.services.memory.redaction import (
    TOKEN_PATTERN,
    MemoryRedactor,
    _SECRET_MASK,
)
from backend.services.memory.repository import MemoryRepository
from backend.services.memory.schemas import MemoryCreate


@pytest.fixture(scope="module")
def redactor() -> MemoryRedactor:
    """Real redactor: exercises the actual Presidio + Fernet pipeline."""
    return MemoryRedactor()


# ---------------------------------------------------------------------------
# 1. PII is never stored in original form
# ---------------------------------------------------------------------------
class TestPIIRedaction:
    def test_email_is_redacted(self, redactor: MemoryRedactor):
        content = "Please reach out to john.doe@example.com about the invoice."
        out = redactor.redact(content)
        assert "john.doe@example.com" not in out
        assert TOKEN_PATTERN.search(out) is not None
        assert "EMAIL_ADDRESS" in out

    def test_phone_number_is_redacted(self, redactor: MemoryRedactor):
        content = "Call me back at 415-555-2671 tomorrow."
        out = redactor.redact(content)
        assert "415-555-2671" not in out
        assert "PHONE_NUMBER" in out

    def test_credit_card_is_redacted(self, redactor: MemoryRedactor):
        content = "Card on file: 4532015112830366 expires next year."
        out = redactor.redact(content)
        assert "4532015112830366" not in out
        assert "CREDIT_CARD" in out

    def test_ssn_is_redacted(self, redactor: MemoryRedactor):
        content = "SSN for verification: 219-09-9999."
        out = redactor.redact(content)
        assert "219-09-9999" not in out
        assert "US_SSN" in out

    def test_redaction_is_reversible_via_decrypt(self, redactor: MemoryRedactor):
        """Tokens must carry real ciphertext that decrypts back to the source PII."""
        from backend.services.memory.redaction import get_memory_encryptor

        content = "Email me at jane.smith@example.com"
        out = redactor.redact(content)
        match = TOKEN_PATTERN.search(out)
        assert match is not None
        entity_type, versioned_ciphertext = match.group(1), match.group(2)
        assert entity_type == "EMAIL_ADDRESS"
        decrypted = get_memory_encryptor().decrypt(versioned_ciphertext)
        assert decrypted == "jane.smith@example.com"

    def test_idempotent_on_already_redacted_content(self, redactor: MemoryRedactor):
        """Re-running redact on already-redacted text must not double-encrypt."""
        content = "Contact: alice@example.com"
        once = redactor.redact(content)
        twice = redactor.redact(once)
        assert once == twice


